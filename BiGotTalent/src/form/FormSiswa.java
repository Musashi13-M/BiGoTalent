    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {                                          
         try {
            String selectedItem = cmbLomba.getSelectedItem().toString();
            String idLomba = selectedItem.split(" - ")[0]; // Ambil ID lomba di depan
            
            Connection c = koneksi.configDB();
            
            // Cek apakah sudah pernah daftar
            String sqlCek = "SELECT * FROM pendaftaran WHERE user_id = ?";
            PreparedStatement pstCek = c.prepareStatement(sqlCek);
            pstCek.setInt(1, idLoginSiswa);
            ResultSet r = pstCek.executeQuery();
            
            if (r.next()) {
                JOptionPane.showMessageDialog(this, "Anda sudah terdaftar di lomba!");
                return;
            }
            
            // Lakukan Insert jika belum terdaftar
            String sqlInsert = "INSERT INTO pendaftaran (user_id, lomba_id, status) VALUES (?, ?, ?)";
            PreparedStatement pstInsert = c.prepareStatement(sqlInsert);
            pstInsert.setInt(1, idLoginSiswa);
            pstInsert.setString(2, idLomba);
            pstInsert.setString(3, "Dokumen dalam Tinjauan");
            
            pstInsert.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Pendaftaran Berhasil! Menunggu verifikasi admin.");
            cekStatusSiswa(); // Refresh status label
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mendaftar: " + e.getMessage());
        }  
    }                                         

